RULES = """\
Rules
-----

- **Same work.** Same parameters, same number of bits, vectors, frames or samples
  for every library; every library draws its own bits and noise with its own
  generator and independent seeds, from the same distributions, so the results agree
  statistically, not bit for bit (the input field of the split-step case and the LLRs
  of the case "same LLRs" are identical in every library).
- **Confidence intervals.** 95 % intervals: Wilson's for independent errors; for coded
  frames and MIMO vectors, whose errors come in bursts, the interval of the mean of
  the per-frame (per-vector) error counts. A result *agrees* when every point lies
  within four standard errors of the closed form (or of comnum, when there is no
  closed form; points without errors on both sides are skipped).
- **Timing.** ``time.perf_counter``; one warm-up run first, reported apart as *first
  call* (it contains the numba compilation, from an empty cache, and the lazy
  initialisations of PyTorch); then the median of five timed runs. The times are per
  unit of work (bit, vector, frame, propagation).
- **Threads.** Every library runs in its own process. *1 thread*: ``OMP_NUM_THREADS``,
  ``OPENBLAS_NUM_THREADS``, ``MKL_NUM_THREADS``, ``VECLIB_MAXIMUM_THREADS``,
  ``NUMBA_NUM_THREADS`` and ``RAYON_NUM_THREADS`` set to 1, ``torch.set_num_threads(1)``,
  ``threads=1`` for ``comnum.run_spec`` and ``--threads 1`` for the binary. *All
  threads*: the defaults of every library (every core; ``threads=0`` for comnum). The
  functions of comnum are single-threaded; its Monte Carlo runner (``run_spec``, the
  binary) runs the trials in parallel.
- **Precision.** What every library computes in is stated next to its times: comnum in
  float64 (float32 on request for the split-step), komm in float64, Sionna in float32
  by default, OptiCommPy in float64 except its Gray constellations (complex64) and its
  LDPC decoder (float32 by default).
- **Sionna** 2.x is built on PyTorch (not TensorFlow); it runs eagerly, under
  ``torch.inference_mode()``, without ``torch.compile``: on the CPU in the modes *1
  thread* and *all threads*, and on the GPU in the mode *GPU* (``--threads gpu``:
  ``torch.set_default_device("cuda")``, every tensor of the chain on the device, the
  result brought back to the host inside the timed call). comnum, komm and OptiCommPy
  have no GPU path: in the GPU column they do not run, and the comparison is Sionna on
  the device against comnum on the CPU of the same machine.
- **OptiCommPy without numba** means ``NUMBA_DISABLE_JIT=1``: numba's own switch, which
  runs every ``@njit`` function of OptiCommPy as plain Python (OptiCommPy has no option
  of its own). Its results are those of the compiled code; it is timed only.

Limits of this comparison
-------------------------

- **The CPU of a laptop, and a GPU.** Sionna is designed for GPUs, large batches,
  learning and automatic differentiation. The first set of results runs it on the CPU
  of the same machine as comnum, eagerly, without ``torch.compile``: its home ground is
  elsewhere. A second set, when present below, runs the same scripts on a machine with
  a GPU, Sionna on the device and comnum on that machine's CPU; comnum has no GPU
  path, so that comparison is one of a CPU library against an accelerator, which is
  what a user choosing between the two faces.
- **Python libraries only.** komm, OptiCommPy and Sionna are NumPy, numba and PyTorch
  code. Specialised C++ libraries (AFF3CT, SIMD decoders) are not timed here: the
  decoders of comnum are timed against those of AFF3CT, one thread, in
  :doc:`comparisons <comparisons>`.
- **Precision.** comnum computes in float64, Sionna in float32 by default: the faster
  library is not always doing less work, but the two are not strictly the same
  computation.
- **One machine, cases chosen by comnum.** The scenarios are the classical links that
  several libraries offer; other machines, sizes and cases may rank the libraries
  differently. The scripts are published to be rerun.
- **What this benchmark changed in comnum.** Over flat Rayleigh fading the first run
  found the comnum functions 3.4 times slower than Sionna on one thread (293 against
  87 ns per bit for BPSK): the linear detector built a dozen 1 × 1 matrices for every
  symbol. It now has a single-stream path (the same filter, as scalars), with the same
  error counts at every point, and the binding passes the vectors without a copy.
- **Why Sionna is fast on a CPU.** It processes the whole batch in one call per
  operation: the cost of Python is paid once per operation, not once per symbol, and
  the kernels of PyTorch are vectorised C++ working in float32.
"""


MODE_NAMES = {"1": "1 thread", "all": "all threads", "gpu": "GPU"}


def load(results_dir=RESULTS) -> dict[str, dict]:
    out = {}
    for s in SCENARIOS:
        path = results_dir / f"{s}.json"
        if path.exists():
            out[s] = json.loads(path.read_text(encoding="utf-8"))
    return out


def other_machines() -> dict[str, dict[str, dict]]:
    """The result sets of other machines: the subdirectories of ``results/`` that hold
    scenario files (``run_all.py --results results/<name>``), by name."""
    out = {}
    for d in sorted(p for p in RESULTS.iterdir() if p.is_dir() and not p.name.startswith("_")):
        results = load(d)
        if results:
            out[d.name] = results
    return out


def heading(text: str, ch: str) -> list[str]:
    return [text, ch * len(text), ""]


def rubric(text: str) -> list[str]:
    """A heading without a target (the cases repeat from one scenario to the next)."""
    return [f".. rubric:: {text}", ""]


def indent(lines: list[str], n: int = 3) -> list[str]:
    return [(" " * n + x) if x else "" for x in lines]


def sci(x: float | None) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "—"
    if x == 0:
        return "0"
    e = math.floor(math.log10(abs(x)))
    m = x / 10**e
    if abs(m) >= 9.995:
        m, e = m / 10, e + 1
    return f"{m:.2f}e{e}"


def num(x: float | None) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "—"
    if x >= 100:
        return f"{x:.0f}"
    if x >= 10:
        return f"{x:.1f}"
    if x >= 1:
        return f"{x:.2f}"
    return f"{x:.3g}"


def runs_by(data: dict) -> dict[tuple[str, str], dict]:
    return {(r["library"], r["threads"]): r for r in data["runs"]}


def case_results(run: dict | None, case: str) -> list[dict]:
    if not run or "cases" not in run:
        return []
    return [c for c in run["cases"] if c["case"] == case]


def se_of(p: dict) -> float:
    if "se" in p:
        return p["se"]
    return (p["hi"] - p["lo"]) / (2 * 1.96)


def agreement(points: list[dict], base: list[dict] | None) -> tuple[str, float | None]:
    """Max |z| against the theory, else against comnum (``base``)."""
    zs = [abs(p["z"]) for p in points if p.get("z") is not None and not math.isnan(p["z"])]
    if zs:
        return "theory", max(zs)
    if base is None:
        return "", None
    zs = []
    for i in range(min(len(points), len(base))):
        p, q = points[i], base[i]
        if p["errors"] == 0 and q["errors"] == 0:
            continue
        s = math.hypot(se_of(p), se_of(q))
        if s > 0:
            zs.append(abs(p["value"] - q["value"]) / s)
    return ("comnum", max(zs)) if zs else ("comnum", None)


def support_table(data: dict, libs: list[str]) -> list[str]:
    rows = []
    for case, sup in data["support"].items():
        row = [CASE_NAMES.get(case, case)]
        for lib in libs:
            s = sup.get(lib)
            row.append("yes" if s is True else (f"not available: {s}" if s else "not run"))
        rows.append(row)
    return rst_table(["Case", *[NAMES[x] for x in libs]], rows)


def present_libs(data: dict) -> list[str]:
    have = {r["library"] for r in data["runs"]} | {
        lib for sup in data["support"].values() for lib, s in sup.items() if s is not True
    }
    return [x for x in ORDER if x in have]


def failures(data: dict) -> list[str]:
    out = []
    for r in data["runs"]:
        if "error" in r:
            msg = r["error"].strip().splitlines()[-1] if r["error"].strip() else "failed"
            out.append(
                f"- {NAMES[r['library']]}, {MODE_NAMES.get(r['threads'], r['threads'])}: failed (``{msg}``)."
            )
    return [*out, ""] if out else []


def error_rate_section(data: dict, libs: list[str], metric: str = "ber") -> list[str]:
    runs = runs_by(data)
    out = []
    for case in data["support"]:
        entries = []
        for lib in libs:
            for c in case_results(runs.get((lib, "1")), case):
                if "points" in c:
                    entries.append((lib, c))
        if not entries:
            continue
        base = next((c["points"] for lib, c in entries if lib == "comnum"), None)
        out += rubric(f"{CASE_NAMES.get(case, case)}: error rates")
        # agreement summary
        rows = []
        for lib, c in entries:
            pts = c["points"] if metric == "ber" else [p["bler"] for p in c["points"]]
            b = base if metric == "ber" else ([p["bler"] for p in base] if base else None)
            ref, z = agreement(pts, None if lib == "comnum" else b)
            coded = "bler" in c["points"][0]
            zb = None
            if coded and lib != "comnum" and base:
                _, zb = agreement([p["bler"] for p in c["points"]], [p["bler"] for p in base])
            worst = max((x for x in (z, zb) if x is not None), default=None)
            verdict = "—" if worst is None else ("yes" if worst <= Z_MAX else "no")
            row = [NAMES[lib], c.get("precision", ""), ref or "—", num(z) if z is not None else "—"]
            if coded:
                row.append(num(zb) if zb is not None else "—")
            rows.append([*row, verdict, pts[0].get("ci", "")])
        coded = "bler" in entries[0][1]["points"][0]
        cols = ["Library", "Precision", "Against", "max abs(z), BER"] + (
            ["max abs(z), FER"] if coded else []
        )
        out += rst_table([*cols, "Agrees", "BER interval"], rows)
        # the values
        xs = [p["ebn0_db"] for p in entries[0][1]["points"]]
        theo = [p.get("theory", p.get("union_bound")) for p in entries[0][1]["points"]]
        has_theory = any(t is not None for t in theo)
        header = ["Eb/N0 (dB)"]
        if has_theory:
            header.append("union bound" if case == "conv" else "theory")
        header += [NAMES[lib] for lib, _ in entries]
        rows = []
        for i, x in enumerate(xs):
            row = [f"{x:g}"]
            if has_theory:
                row.append(sci(theo[i]))
            for _, c in entries:
                p = c["points"][i]
                row.append(f"{sci(p['value'])} [{sci(p['lo'])}, {sci(p['hi'])}]")
            rows.append(row)
        n_bits = entries[0][1]["points"][0]["total"]
        out += [
            f".. dropdown:: BER and its 95 % interval, every point ({n_bits:,} bits per point)",
            "",
        ]
        out += indent(rst_table(header, rows))
        if any("bler" in p for p in entries[0][1]["points"]):
            rows = []
            for i, x in enumerate(xs):
                row = [f"{x:g}"]
                for _, c in entries:
                    q = c["points"][i]["bler"]
                    row.append(f"{sci(q['value'])} [{sci(q['lo'])}, {sci(q['hi'])}]")
                rows.append(row)
            n_frames = entries[0][1]["points"][0]["bler"]["total"]
            out += [
                f".. dropdown:: Frame error rate and its 95 % interval ({n_frames:,} frames per point)",
                "",
            ]
            out += indent(rst_table(["Eb/N0 (dB)", *[NAMES[lib] for lib, _ in entries]], rows))
    return out


def timing_section(
    data: dict, libs: list[str], key: str = "timing", title: str = "time"
) -> list[str]:
    runs = runs_by(data)
    out = []
    for case in data["support"]:
        variants: dict[tuple[str, str], dict[str, dict]] = {}
        for lib in libs:
            for t in data["thread_modes"]:
                for c in case_results(runs.get((lib, t)), case):
                    if key in c:
                        variants.setdefault((lib, c.get("variant", "")), {})[t] = c
        if not variants:
            continue
        any_c = next(iter(next(iter(variants.values())).values()))
        unit_label, factor = UNITS[any_c[key]["unit"]]
        base = variants.get(("comnum", "f64" if case == "ssfm" else ""), {}).get("1")
        base_t = base[key]["median_s"] / base[key]["units"] if base else None
        rows = []
        for (lib, variant), by_t in variants.items():
            c1 = by_t.get("1") or next(iter(by_t.values()))
            name = NAMES[lib] + (f", {variant}" if variant else "")
            row = [name, c1.get("precision", "")]
            for t in data["thread_modes"]:
                c = by_t.get(t)
                row.append(num(c[key]["median_s"] / c[key]["units"] * factor) if c else "—")
            t1 = by_t.get("1")
            rel = (t1[key]["median_s"] / t1[key]["units"]) / base_t if (t1 and base_t) else None
            row.append(num(rel) if rel is not None else "—")
            first = c1.get("first_call_s", c1[key].get("warmup_s"))
            row.append(f"{first:.3g} s" if first is not None else "—")
            rows.append(row)
        workload = any_c[key]["workload"]
        modes = [MODE_NAMES.get(t, t) for t in data["thread_modes"]]
        out += rubric(f"{CASE_NAMES.get(case, case)}: {title}")
        out += [
            f"Median of {any_c[key]['repeats']} runs, {unit_label}; workload: {workload}. "
            "*Relative*: the 1-thread time over that of comnum (functions) on 1 thread.",
            "",
        ]
        out += rst_table(["Library", "Precision", *modes, "Relative", "First call"], rows)
    return out


def scenario_section(name: str, data: dict) -> list[str]:
    libs = present_libs(data)
    out = heading(data["title"], "-")
    out += [data["description"], ""]
    out += ["Parameters:", ""]
    for k, v in data["parameters"].items():
        key = {"ebn0_db": "Eb/N0 (dB)", **CASE_NAMES}.get(k, k.replace("_", " "))
        out.append(f"- {key}: {v if not isinstance(v, list) else ', '.join(f'{x:g}' for x in v)}")
    out += ["", f"Script: `{data['script']} <{REPO}/{data['script']}>`_.", ""]
    out += [
        ".. dropdown:: The script",
        "",
        f"   .. literalinclude:: ../../{data['script']}",
        "      :language: python",
        "",
    ]
    out += rubric("Support")
    out += support_table(data, libs)
    out += failures(data)
    if name == "s5_ssfm":
        out += ssfm_section(data)
    else:
        out += error_rate_section(data, libs)
    if name == "s4_coding":
        out += same_llr_section(data)
        out += timing_section(data, libs, "timing", "decoder time")
        out += timing_section(data, libs, "timing_chain", "whole-chain time")
    else:
        out += timing_section(data, libs)
    out += [".. dropdown:: The commands of every run", "", "   .. code-block:: bash", ""]
    for r in data["runs"]:
        if "command" in r:
            out.append(f"      {r['command']}")
    out.append("")
    return out


def same_llr_section(data: dict) -> list[str]:
    totals: dict[str, list[int]] = {}
    for r in data.get("agreement", {}).get("same_llr_vs_comnum", []):
        t = totals.setdefault(r["library"], [0, 0, 0, 0])
        t[0] += 1
        t[1] += r["frames"]
        t[2] += r["same_bit_errors"]
        t[3] += r["same_frame_outcome"]
    if not totals:
        return []
    rows = [
        [
            NAMES[lib],
            f"{t[0]}",
            f"{t[1]}",
            f"{t[2]} ({100 * t[2] / t[1]:.2f} %)",
            f"{t[3]} ({100 * t[3] / t[1]:.2f} %)",
        ]
        for lib, t in totals.items()
    ]
    out = rubric("Same LLRs: the decisions frame by frame")
    out += [
        "The decoders received identical LLRs. Over all the points: the frames where a library "
        "makes as many bit errors as comnum, and the frames it decodes (or fails to decode) as "
        "comnum does.",
        "",
    ]
    return out + rst_table(
        ["Library", "Points", "Frames", "Same bit errors", "Same frame outcome"], rows
    )


def ssfm_section(data: dict) -> list[str]:
    ag = data.get("agreement", {})
    rows = []
    names = {
        "comnum_f64": "comnum, float64",
        "comnum_f32": "comnum, float32",
        "opticommpy_f64": "OptiCommPy, float64",
        "sionna_single": "Sionna, float32",
        "sionna_double": "Sionna, float64",
        "sionna_single_plain": "Sionna, float32, its own convention (not conjugated)",
        "sionna_double_plain": "Sionna, float64, its own convention (not conjugated)",
    }
    for r in ag.get("nmse", []):
        rows.append(
            [
                names.get(r["field"], r["field"]),
                sci(r["nmse_vs_comnum_f64"]),
                sci(r["nmse_vs_reference"]),
            ]
        )
    if not rows:
        return []
    out = rubric("Output fields")
    out += [
        f"NMSE of the output field, ``sum |a - b|^2 / sum |b|^2``, against comnum in float64 "
        f"at the same step and against the step-converged reference (comnum, "
        f"{ag.get('reference_step_km', 0.05):g} km). The NMSE against the reference is the "
        "error of the 1 km step itself.",
        "",
    ]
    return out + rst_table(["Field", "NMSE vs comnum (float64, 1 km)", "NMSE vs reference"], rows)


def machine_section(data: dict) -> list[str]:
    m, g, v = data["machine"], data["git"], data["versions"]
    cores = f"{m['logical_cores']} logical"
    if m.get("core_levels"):
        cores += " (" + ", ".join(lv.lower() for lv in m["core_levels"]) + ")"
    out = heading("Machine and versions", "-")
    rows = [
        ["CPU", m.get("cpu") or "—"],
        ["Cores", cores],
        ["Memory", f"{m.get('ram_gb')} GB"],
    ]
    if m.get("gpu"):
        gpu = m["gpu"]
        text = (
            f"{gpu['name']}, {gpu['memory']}, driver {gpu['driver']}"
            if isinstance(gpu, dict)
            else str(gpu)
        )
        rows.append(["GPU", text])
    rows += [
        [
            "System",
            f"macOS {m['macos']}" if m.get("macos") else (m.get("linux") or m.get("platform", "—")),
        ],
        ["Python", m.get("python", "—")],
        ["Rust", m.get("rustc") or "—"],
        [
            "comnum commit",
            f"``{(g.get('commit') or '?')[:12]}``"
            + (" (with uncommitted changes)" if g.get("dirty") else ""),
        ],
        ["Generated", data["generated_utc"]],
    ]
    for pkg in ["comnum", "komm", "OptiCommPy", "sionna", "torch", "numba", "numpy", "scipy"]:
        rows.append([pkg, v.get(pkg) or "not installed"])
    return out + rst_table(None, rows, [30, 70])


def libraries_section(data: dict) -> list[str]:
    out = heading("Libraries", "-")
    rows = []
    for lib in ORDER:
        if lib in data["libraries"]:
            rows.append(
                [NAMES[lib], data["libraries"][lib], data["versions"].get(VERSION_OF[lib]) or "—"]
            )
    return out + rst_table(["Name on this page", "What runs", "Version"], rows, [22, 63, 15])


