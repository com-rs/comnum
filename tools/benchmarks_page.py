def render() -> str:
    results = load()
    lines = [INTRO]
    if not results:
        lines += ["No results yet: run ``benchmarks/libraries/run_all.py`` (see below).", ""]
        lines += [RULES, REPRODUCE.format(repo=REPO)]
        return "\n".join(lines).rstrip() + "\n"
    first = next(iter(results.values()))
    if any(d["quick"] for d in results.values()):
        lines += [
            ".. warning::",
            "",
            "   These results come from a ``--quick`` run: small sizes, wide intervals, and",
            "   timings that mean nothing. Run ``run_all.py`` without ``--quick`` on a quiet",
            "   machine.",
            "",
        ]
    lines += [RULES]
    lines += libraries_section(first)
    lines += machine_section(first)
    lines += [REPRODUCE.format(repo=REPO)]
    for name, data in results.items():
        lines += scenario_section(name, data)
    for machine, results in other_machines().items():
        lines += other_machine_section(machine, results)
    return "\n".join(lines).rstrip() + "\n"


def other_machine_section(name: str, results: dict[str, dict]) -> list[str]:
    """The same scenarios on another machine (``results/<name>/``): its machine table,
    then the scenario sections, with the mode *GPU* when it was run."""
    first = next(iter(results.values()))
    m = first["machine"]
    gpu = m.get("gpu")
    gpu_name = gpu["name"] if isinstance(gpu, dict) else gpu
    out = heading(f"On another machine: {name}" + (f" ({gpu_name})" if gpu_name else ""), "=")
    out += [
        f"The same scripts, run on a second machine (``run_all.py --results results/{name}``):"
        + (
            " Sionna on its GPU in the column *GPU*, and every library on its CPU in the"
            " other columns. The *Relative* column stays the 1-thread time over that of"
            " comnum (functions) on 1 thread of this machine."
            if any("gpu" in d["thread_modes"] for d in results.values())
            else " every library on its CPU."
        ),
        "",
    ]
    if any(d["quick"] for d in results.values()):
        out += [".. warning::", "", "   A ``--quick`` run: the timings mean nothing.", ""]
    out += machine_section(first)
    for s, data in results.items():
        out += scenario_section(s, data)
    return out


