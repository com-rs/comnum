#!/usr/bin/env python3
"""The comparisons of comnum with the literature, in `docs/LITERATURE.md`.

The source is `validation/literature.yaml`: one entry per document (paper, standard,
reference implementation), with what is compared, the tests that compare it, a badge
and the inconsistencies found in the document. `just literature` regenerates the page;
`--check` (run by `just check` and CI) fails if the page is out of date or if a test
named in the file does not exist (`path` must exist, `path::name` must define the
test `name`: `fn name(` in Rust, `def name(` in Python).
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter

import yaml
from _common import ROOT, THEME_TITLES, fail, missing_test, write_or_check
from cards import cards

SOURCE = ROOT / "validation" / "literature.yaml"
OUTPUT = ROOT / "docs" / "LITERATURE.md"
BADGES = {"green": "🟢", "orange": "🟠", "red": "🔴"}
# the themes of the documentation, in the order of a link (as the API reference, the
# gallery and the maturity table), then the reference implementations
AREAS = [*THEME_TITLES, "Reference implementations"]
# what the expected values of a card are (`evidence` of validation/cards/README.md)
EVIDENCE = {
    "closed_form": "closed form",
    "table": "table",
    "curve": "curve",
    "claim": "claim",
    "recording": "recording",
}


def check_tests(entries: list[dict]) -> list[str]:
    """The tests named in the file that do not exist."""
    return [
        f"{e['id']}: {why}"
        for e in entries
        for t in e.get("tests", [])
        if (why := missing_test(*t.split("::", 1)))
    ]


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(entries: list[dict]) -> str:
    count = Counter(e["badge"] for e in entries)
    by_entry: dict[str, list[str]] = {}
    evidence: dict[str, set[str]] = {}
    for c in cards():
        by_entry.setdefault(c.get("literature", ""), []).append(c["id"])
        evidence.setdefault(c.get("literature", ""), set()).update(c["evidence"])
    kinds = Counter(k for e in entries for k in evidence.get(e["id"], ()))
    out = [
        "# Comparisons with the literature",
        "",
        "<!-- generated by tools/literature_table.py from validation/literature.yaml: do not edit -->",
        "",
        "Every document that comnum is compared with: what is compared, the tests that do it",
        "(and the validation cards that hold the expected values, `just card <id>` to rerun",
        "one), and the inconsistencies found in the document itself. Every entry names its",
        "document (the files are not distributed); the evidence per module is in",
        "[`MATURITY.md`](MATURITY.md).",
        "",
        "- 🟢 **reproduced**: the published values (tables, closed forms, points of figures within",
        "  a stated tolerance, claims of the text) are reproduced by automated tests;",
        "- 🟠 **partly**: a qualitative comparison, a loose tolerance, a subset of the document,",
        "  values quoted without the document, or an unexplained gap;",
        "- 🔴 **not compared**: the code follows the document, no test checks its values.",
        "",
        "The column *Evidence* says what the expected values of the cards of a document are:",
        "a **closed form** evaluated, a **table** (numbers printed in a table or the text,",
        "verbatim), a **curve** (points read on a figure), a **claim** of the text (a range),",
        "a **recording** of a reference tool (`validation/cards/README.md`); a dash for a",
        "document compared by tests without a card.",
        "",
        "The last column lists the inconsistencies found in the documents (misprints, figures",
        "that contradict the text); they do not lower the badge when the corrected result is",
        "reproduced.",
        "",
        f"Summary: {len(entries)} documents, {count['green']} 🟢, {count['orange']} 🟠, "
        f"{count['red']} 🔴; {sum(len(e.get('remarks', [])) for e in entries)} inconsistencies found; "
        "documents with cards of each evidence: "
        + ", ".join(f"{kinds[k]} {label}" for k, label in EVIDENCE.items())
        + ".",
    ]
    for area in AREAS:
        rows = [e for e in entries if e["area"] == area]
        if not rows:
            continue
        out += [
            "",
            f"## {area}",
            "",
            "| | Document | Module | Evidence | Compared | Tests | Not covered | Inconsistencies in the document |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for e in rows:
            tests = [f"`{t}`" for t in e.get("tests", [])]
            tests += [
                f"card [`{c}`](../validation/cards/{c}.yaml)" for c in by_entry.get(e["id"], [])
            ]
            tests = "<br>".join(tests) or "—"
            remarks = "<br>".join(f"• {cell(r)}" for r in e.get("remarks", [])) or "—"
            kind = (
                ", ".join(v for k, v in EVIDENCE.items() if k in evidence.get(e["id"], ())) or "—"
            )
            out.append(
                f"| {BADGES[e['badge']]} | {cell(e['ref'])} | `{cell(e['module'])}` | {kind} | "
                f"{cell(e['tested'])} | {tests} | {cell(e.get('not_covered', '—'))} | {remarks} |"
            )
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check", action="store_true", help="fail if the page is stale or a test is missing"
    )
    args = ap.parse_args()
    entries = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    unknown = [e["id"] for e in entries if e["badge"] not in BADGES or e["area"] not in AREAS]
    if unknown:
        print(f"unknown badge or area: {unknown}", file=sys.stderr)
        return 1
    missing = check_tests(entries)
    if missing:
        return fail("tests named in validation/literature.yaml that do not exist:", missing)
    return write_or_check(OUTPUT, render(entries), args.check, fix="`just literature`")


if __name__ == "__main__":
    sys.exit(main())
