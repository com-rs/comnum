#!/usr/bin/env python3
"""The maturity of the modules of comnum, in `docs/MATURITY.md`, the summary of `README.md`
and `docs/python/maturity.rst`.

The source is `validation/maturity.yaml`: one entry per module, with its theme, its
level, the strongest evidence in a few words, the tests that give the evidence and the
regimes not covered yet. The three pages group the modules by the themes of the
documentation, in the order of a link (as the API reference, the gallery and
`docs/LITERATURE.md`). `just maturity` regenerates them; `--check` (run by
`just check` and CI) fails if one of them is out of date or if a test cited in the
evidence does not exist (`path` must exist, `path::name` must define the last part of
`name`, a test or a module: `fn name(`, `mod name` in Rust, `def name(` in Python).
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

import yaml
from _common import (
    ROOT,
    THEME_TITLES,
    fail,
    md_to_rst,
    missing_test,
    rst_table,
    splice,
    write_or_check,
)
from cards import cards, runner

SOURCE = ROOT / "validation" / "maturity.yaml"
MATURITY = ROOT / "docs" / "MATURITY.md"
README = ROOT / "README.md"
PYTHON = ROOT / "docs" / "python" / "maturity.rst"
# the generated part of README.md and of docs/python/maturity.rst lies between these
BEGIN = "generated by tools/maturity_table.py from validation/maturity.yaml: do not edit"
END = "end of the generated table"

INTRO = """# Maturity of the modules

<!-- {begin} -->

For every module a user sees, the strongest evidence that it is right, the tests that
give it, and what is not covered yet, grouped by the themes of the documentation.
Built from the tests of the repository (the `literature` unit tests,
`validation/tests/*.rs`, the specifications with `expect`, the Python tests); the
source is `validation/maturity.yaml`, to update when a validation is added.

**Levels.** Computed from the kind of every item of evidence (`recording`, `table`,
`curve`, `claim`, `closed_form`, `self`, the `evidence` of the validation cards plus
self-consistency), not given by hand; an item that cites a validation card has one of
the kinds of that card.

- **A** — validated against an external reference: a published figure, table or
  claim of the text, a table of a standard reproduced verbatim, or the recorded output
  of a reference implementation (OptiCommPy 0.11, GNPy 3.0, AFF3CT v4.7.1) on the same
  inputs.
- **B** — against a closed form only.
- **C** — self-consistency only: round trips, invariants, comparisons between the
  blocks of the library.
- **—** — not validated.

A level says what is checked, not that every regime is: the last column lists the
regimes and references not covered; the comparisons with every document are in
[`LITERATURE.md`](LITERATURE.md). Tests marked "ignored" run with
`cargo test --release -p comnum-validation -- --ignored`, by hand or by the workflow
`validation.yml` started by hand (never automatically); the others run on every push.
A specification run "on demand" is checked by `comnum verify <file>` (`just validate`
for `specs/validation/`).
"""


# the kinds of an item of evidence: the `evidence` of the validation cards, and `self`
# for self-consistency (round trips, invariants, a simulation against the library's
# own closed form)
KINDS = ["recording", "table", "curve", "claim", "closed_form", "self"]
# the level of a module, from the kinds of its evidence: an external reference (a
# recording, a table, a curve or a claim of a document), a closed form, self-consistency
LEVELS = [("A", {"recording", "table", "curve", "claim"}), ("B", {"closed_form"}), ("C", {"self"})]


def level(kinds: set[str]) -> str:
    return next((name for name, these in LEVELS if kinds & these), "—")


def load() -> list[dict]:
    """The entries, with the level computed from the kinds of their evidence and the
    evidence as the cell of docs/MATURITY.md ("• " items separated by "<br>")."""
    entries = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    for e in entries:
        if e["theme"] not in THEME_TITLES:
            raise SystemExit(f"{e['name']}: unknown theme {e['theme']!r}")
        if "level" in e:
            raise SystemExit(f"{e['name']}: the level is computed from the evidence, not given")
        items = [next(iter(item.items())) for item in e["evidence"]]
        unknown = [k for k, _ in items if k not in KINDS]
        if unknown or any(len(item) != 1 for item in e["evidence"]):
            raise SystemExit(f"{e['name']}: an item of evidence is `- <kind>: text`, {KINDS}")
        e["items"] = items
        e["level"] = level({k for k, _ in items})
        texts = [t for _, t in items]
        e["evidence"] = texts[0] if len(texts) == 1 else "<br>".join(f"• {t}" for t in texts)
    return entries


# a path of the repository in inline code, with an optional `::name` of a test
CITED = re.compile(
    r"`((?:crates|validation|tests|specs|bindings|python|docs|benchmarks)/[^`\s:]+)(?:::([\w:]+))?`"
)


def check_tests(entries: list[dict]) -> list[str]:
    """The files and tests cited in the evidence that do not exist."""
    return [
        f"{e['name']}: {why}"
        for e in entries
        for path, name in CITED.findall(e["evidence"])
        if "*" not in path and (why := missing_test(path, name))
    ]


def check_cards(entries: list[dict]) -> list[str]:
    """The items of evidence whose kind is none of the evidence of the cards they cite
    (by their id, or by the test or specification that runs them)."""
    out = []
    for e in entries:
        for kind, text in e["items"]:
            cited = [
                c
                for c in cards()
                if re.search(rf"\b{c['id']}(\.yaml)?\b", text)
                or ("function" not in c["run"] and runner(c)[1].split("::")[0] in text)
            ]
            evidence = {k for c in cited for k in c["evidence"]}
            if cited and kind not in evidence:
                ids = ", ".join(c["id"] for c in cited)
                out.append(
                    f"{e['name']}: an item of kind {kind} cites the cards {ids} ({sorted(evidence)})"
                )
    return out


def summary(entries: list[dict]) -> str:
    count = Counter(e["level"] for e in entries)
    parts = [f"{count[k]} at {k}" for k in ["A", "B", "C", "—"] if count[k]]
    return f"Summary: {len(entries)} modules: " + ", ".join(parts) + "."


def by_theme(entries: list[dict]):
    for theme in THEME_TITLES:
        rows = [e for e in entries if e["theme"] == theme]
        if rows:
            yield theme, rows


def render_maturity(entries: list[dict]) -> str:
    out = [INTRO.format(begin=BEGIN).rstrip(), "", summary(entries)]
    for theme, rows in by_theme(entries):
        out += [
            "",
            f"## {theme}",
            "",
            "| Module | Level | Evidence | Known gaps |",
            "|---|---|---|---|",
        ]
        for e in rows:
            module = f"{e['name']} ({e['modules']})" if e["modules"] else e["name"]
            out.append(f"| {module} | **{e['level']}** | {e['evidence']} | {e['gaps']} |")
    return "\n".join(out) + "\n"


def render_readme(entries: list[dict]) -> str:
    """The summary of README.md, between its marker lines (the tables are in
    docs/MATURITY.md and docs/python/maturity.rst)."""
    return "\n".join(["", summary(entries), ""]) + "\n"


def render_python(entries: list[dict]) -> str:
    """The tables of docs/python/maturity.rst, between its marker lines."""
    out = ["", summary(entries)]
    for theme, rows in by_theme(entries):
        out += ["", theme, "-" * len(theme), ""]
        cells = [
            [
                md_to_rst(e.get("short", e["name"]))
                + ("" if e.get("python", True) else " (Rust only)"),
                e["level"],
                md_to_rst(e["summary"]),
            ]
            for e in rows
        ]
        out += rst_table(["Module", "Level", "Strongest evidence"], cells, [40, 8, 52])[:-1]
    return "\n".join([*out, ""]) + "\n"


def outputs(entries: list[dict]) -> dict[Path, str]:
    return {
        MATURITY: render_maturity(entries),
        README: splice(
            README.read_text(encoding="utf-8"), render_readme(entries), BEGIN, END, README
        ),
        PYTHON: splice(
            PYTHON.read_text(encoding="utf-8"), render_python(entries), BEGIN, END, PYTHON
        ),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a page is out of date")
    args = ap.parse_args()
    entries = load()
    missing = check_tests(entries)
    if missing:
        return fail("tests cited in validation/maturity.yaml that do not exist:", missing)
    disagree = check_cards(entries)
    if disagree:
        return fail("evidence of validation/maturity.yaml that disagrees with its cards:", disagree)
    status = 0
    for path, text in outputs(entries).items():
        status |= write_or_check(path, text, args.check, fix="`just maturity`")
    return status


if __name__ == "__main__":
    sys.exit(main())
