#!/usr/bin/env python3
"""Record the split-step Fourier propagation of Optilux that comnum is compared with.

Optilux (GPL-3.0, Paolo Serena, University of Parma, <https://optilux.sourceforge.io/>,
the release of April 2021) is a MATLAB/Octave toolbox of optical communications. This
script runs its ``fiber`` and ``ampliflat`` under Octave (``tools/record_optilux.m``)
over the link of the split-step scenario of the library benchmark
(``benchmarks/libraries/s5_ssfm.py``: 80 km spans of standard fibre, 1 km symmetric
steps, noiseless amplification) and records the output field of three cases (the
provenance in the ``.json``):

- ``linear_1span``: one span without Kerr effect (dispersion and attenuation);
- ``kerr_1span``: one span with gamma = 1.3 /W/km;
- ``kerr_10spans``: the ten spans of the benchmark.

Two modes, two fixtures:

- ``--mode ssfm`` (``tests/oracle/optilux_ssfm.npz``, read by
  ``tests/oracle/test_optilux_oracle.py``): the scalar NLSE on the input field of the
  benchmark scenario at its quick size (16-QAM at 32 GBd, root-raised cosine of roll-off
  0.1, 4 samples per symbol, 4 dBm, 2¹¹ symbols, seed 1);
- ``--mode manakov`` (``tests/oracle/optilux_manakov.npz``, read by
  ``tests/oracle/test_optilux_manakov_oracle.py``): the Manakov equation in Optilux's
  unique-field mode (``ismanakov``, no PMD and no birefringence) on a dual-polarisation
  WDM field of five 16-QAM channels at 32 GBd spaced by 50 GHz, 2 dBm per channel, 16
  samples per symbol, 2¹¹ symbols, generated by comnum (seed 1: the symbols of every
  channel and polarisation drawn in order from one generator).

Optilux's fields are returned in comnum's convention: Optilux writes the equation with
the opposite sign of the imaginary unit, so the driver propagates the conjugate of the
input and conjugates the result. Optilux is not a dependency of comnum: download
``optilux.zip`` from SourceForge (it is never committed: GPL-3.0 code, for instance
into ``references/tools/optilux/``, which git ignores) and run::

    python tools/record_optilux.py --optilux /path/to/optilux --mode ssfm
    python tools/record_optilux.py --optilux /path/to/optilux --mode manakov

The files are written with the functions of the recorded oracles
(``tests/oracle/__init__.py``): recording again with the same version produces no diff.
"""

from __future__ import annotations

import argparse
import math
import platform
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from _common import ROOT

sys.path.insert(0, str(ROOT / "tests"))
from oracle import DIR as OUT
from oracle import archive, dumps

SEED = 1
N_SYMBOLS = 2**11
SYMBOL_RATE, ROLLOFF, N_TAPS = 32e9, 0.1, 1025
CASES = [("linear_1span", 1, 0.0), ("kerr_1span", 1, 1.0), ("kerr_10spans", 10, 1.0)]
LINK = {
    "alpha_db_km": 0.2,
    "d_ps_nm_km": 17.0,
    "beta3": 0.0,
    "gamma_w_km": 1.3,
    "fc_hz": 193.1e12,
    "span_km": 80.0,
    "step_km": 1.0,
    "amplification": "ideal (noiseless, alpha L at the end of every span)",
}
# the two modes: the scalar field of the benchmark scenario, the dual-polarisation WDM
# field of the Manakov comparison
MODES = {
    "ssfm": {
        "name": "optilux_ssfm",
        "sps": 4,
        "channels": 1,
        "spacing_hz": 0.0,
        "power_dbm": 4.0,
        "polarisations": 1,
    },
    "manakov": {
        "name": "optilux_manakov",
        "sps": 16,
        "channels": 5,
        "spacing_hz": 50e9,
        "power_dbm": 2.0,
        "polarisations": 2,
    },
}


def channel(rng, sps: int, power_w: float) -> np.ndarray:
    """One 16-QAM channel at `power_w` (W), its symbols drawn from `rng`, pulse-shaped
    by the root-raised cosine of the benchmark scenario."""
    import comnum

    c = comnum.Constellation("qam", 16).normalized()
    _, s = comnum.symbols(c, N_SYMBOLS, rng)
    h = comnum.pulse_shape("rrc", sps, n_taps=N_TAPS, rolloff=ROLLOFF)
    x = comnum.pnorm(comnum.fir_filter(h, comnum.upsample(s, sps)))
    return x * math.sqrt(power_w)


def input_field(mode: dict) -> np.ndarray:
    """The input field of the mode, one row per polarisation: the field of
    ``benchmarks/libraries/s5_ssfm.py`` at its quick size (``ssfm``), or the WDM field
    whose channels sit on ``comnum.wdm_grid`` with the power of the mode split equally
    between the polarisations (``manakov``); the symbols of every channel, and of its
    polarisations in turn, are drawn in order from one generator."""
    import comnum

    rng = comnum.Rng(SEED)
    fs = SYMBOL_RATE * mode["sps"]
    n_pol = mode["polarisations"]
    power_w = comnum.dbm2w(mode["power_dbm"]) / n_pol
    field = np.zeros((n_pol, N_SYMBOLS * mode["sps"]), dtype=np.complex128)
    for f in comnum.wdm_grid(mode["channels"], mode["spacing_hz"]):
        for p in range(n_pol):
            field[p] += comnum.freq_shift(channel(rng, mode["sps"], power_w), f, fs)
    return field


def run_optilux(optilux: Path, x: np.ndarray, fs: float, n_spans: int, gamma_scale: float) -> tuple:
    """The field (one row per polarisation) after ``n_spans`` spans of Optilux, in
    comnum's convention, and the number of steps of every span."""
    script = ROOT / "tools" / "record_optilux.m"
    with tempfile.TemporaryDirectory() as tmp:
        src, dst = Path(tmp) / "in.csv", Path(tmp) / "out.csv"
        xc = np.conj(x)
        columns = [c for row in xc for c in (row.real, row.imag)]
        np.savetxt(src, np.column_stack(columns), delimiter=",", fmt="%.17g")
        cmd = [
            "octave", "--no-gui", "--quiet", str(script), str(optilux), str(src), str(dst),
            str(n_spans), repr(gamma_scale), repr(fs / 1e9),
        ]  # fmt: skip
        proc = subprocess.run(cmd, capture_output=True, text=True, check=True)
        out = np.loadtxt(dst, delimiter=",")
    steps = [int(v) for v in re.findall(r"\d+", proc.stdout.strip().splitlines()[-1])]
    y = np.stack([np.conj(out[:, 2 * p] + 1j * out[:, 2 * p + 1]) for p in range(len(x))])
    return y, steps


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--optilux", required=True, type=Path, help="the directory of Optilux")
    p.add_argument("--mode", choices=sorted(MODES), default="ssfm", help="the fixture")
    args = p.parse_args()
    mode = MODES[args.mode]
    name = mode["name"]
    readme = (args.optilux / "README").read_text(encoding="utf-8", errors="replace")
    m = re.search(r"Optilux,\s*([A-Za-z]+ \d{4})", readme)
    version = m.group(1) if m else "unknown"
    octave = subprocess.run(["octave", "--version"], capture_output=True, text=True, check=True)
    octave_version = octave.stdout.splitlines()[0]

    fs = SYMBOL_RATE * mode["sps"]
    x = input_field(mode)
    scalar = mode["polarisations"] == 1
    arrays = {"input": x[0] if scalar else x}
    steps: dict[str, list[int]] = {}
    for case, n_spans, gamma_scale in CASES:
        y, steps[case] = run_optilux(args.optilux, x, fs, n_spans, gamma_scale)
        arrays[case] = y[0] if scalar else y
        print(f"{case}: {y.shape[1]} samples, steps per span {steps[case]}")
    if scalar:
        signal = (
            f"16-QAM, {SYMBOL_RATE / 1e9:g} GBd, RRC roll-off {ROLLOFF}, {mode['sps']} samples "
            f"per symbol, {mode['power_dbm']} dBm, {N_SYMBOLS} symbols, seed {SEED} (comnum)"
        )
        equation = "the scalar NLSE (one polarisation)"
    else:
        signal = (
            f"{mode['channels']} channels of 16-QAM at {SYMBOL_RATE / 1e9:g} GBd spaced by "
            f"{mode['spacing_hz'] / 1e9:g} GHz (comnum.wdm_grid), RRC roll-off {ROLLOFF}, "
            f"{mode['sps']} samples per symbol, {mode['power_dbm']} dBm per channel split "
            f"between two polarisations, {N_SYMBOLS} symbols, seed {SEED} (comnum: the "
            "symbols of every channel and polarisation drawn in order from one generator)"
        )
        equation = (
            "the Manakov equation of the unique-field mode (ismanakov true, 8/9 gamma), "
            "no PMD and no birefringence (pmdpar 0: one waveplate, the identity)"
        )
    doc = {
        "name": name,
        "tool": "Optilux",
        "version": version,
        "repository": "https://optilux.sourceforge.io/",
        "license": "GPL-3.0 (the outputs, not the code)",
        "octave": octave_version,
        "python": platform.python_version(),
        "numpy": np.__version__,
        "script": "tools/record_optilux.m (fiber with steptype symm, dzmax 1000 m, "
        "dphi1fwm false, stepupd nlp, dphimax 1e9; ampliflat with the gain alpha L)",
        "equation": equation,
        "signal": signal,
        "link": {**LINK, "fs_hz": fs},
        "cases": {case: {"spans": n, "gamma_scale": g} for case, n, g in CASES},
        "steps_per_span": steps,
        "convention": "the fields are conj(optilux(conj(x))): Optilux writes the NLSE "
        "with the opposite sign of the imaginary unit",
        "units": "sqrt(W)",
        "layout": "one row per polarisation (x, y)" if not scalar else "one polarisation",
        "npz": f"{name}.npz",
    }
    OUT.mkdir(exist_ok=True)
    (OUT / f"{name}.json").write_text(dumps(doc), encoding="utf-8")
    (OUT / f"{name}.npz").write_bytes(archive(arrays))
    print(f"wrote {OUT / name}.json and .npz")
    return 0


if __name__ == "__main__":
    sys.exit(main())
