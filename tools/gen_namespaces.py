#!/usr/bin/env python3
"""Generate the thematic namespaces of the Python package, ``python/comnum/<theme>.py``.

``import comnum`` exports every name at the top level, as before. The namespaces group
the same objects by theme, for discovery by completion: ``comnum.optical.Ssfm`` is
``comnum.Ssfm``, and ``comnum.theory.ber`` is ``comnum.theory_ber`` (the closed forms
lose their ``theory_`` prefix there). They are read from the sections of the API
reference, ``docs/python/api/index.rst``, so that a name documented in a theme is in
its namespace::

    python tools/gen_namespaces.py           # write the modules
    python tools/gen_namespaces.py --check   # fail if one is out of date (CI)

The output is formatted by ``ruff format`` (the ``lint`` dependency group).
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys

from _common import ROOT, ruff_format, write_or_check

INDEX = ROOT / "docs" / "python" / "api" / "index.rst"
PACKAGE = ROOT / "python" / "comnum"

# the themes of the API reference that get a namespace, and its name; Foundations
# (generators, sources, constellations) stays at the top level, and Simulation is
# comnum.sim and the classes of the chains
THEMES = {
    "Coding and shaping": "coding",
    "Waveforms": "waveforms",
    "MIMO": "mimo",
    "Wireless channels": "channels",
    "Optical": "optical",
    "Hardware impairments": "hardware",
    "Receiver DSP": "dsp",
    "Metrics and analysis": "metrics",
    "Systems and standards": "systems",
}
THEORY = "theory"
PREFIX = "theory_"


def themes() -> dict[str, list[str]]:
    """The names of every theme of the API reference, in its order."""
    lines = INDEX.read_text(encoding="utf-8").splitlines()
    out: dict[str, list[str]] = {}
    theme = None
    for line, below in zip(lines, [*lines[1:], ""], strict=True):
        if line.strip() and re.fullmatch(r"-{3,}", below):
            theme = line.strip()
            out[theme] = []
        elif theme and re.fullmatch(r"   [A-Za-z_]\w*", line):
            out[theme].append(line.strip())
    return out


def sorted_imports(text: str, name: str) -> str:
    """`text` with its import block in the order of the linter (`ruff check --select I`)."""
    ruff = shutil.which("ruff")
    if ruff is None:
        raise SystemExit("tools/gen_namespaces.py needs ruff (pip install --group lint)")
    cmd = [
        ruff,
        "check",
        "--config",
        str(ROOT / "pyproject.toml"),
        "--select",
        "I",
        "--fix",
        "--quiet",
    ]
    out = subprocess.run(
        [*cmd, "--stdin-filename", str(PACKAGE / f"{name}.py"), "-"],
        input=text,
        capture_output=True,
        text=True,
    )
    return out.stdout or text


def module(name: str, title: str, intro: str, names: dict[str, str]) -> str:
    """The namespace `name`: `names` maps the name in it to the name in comnum."""
    imports = "\n".join(
        f"    {top}," if alias == top else f"    {top} as {alias},"
        for alias, top in sorted(names.items(), key=lambda item: item[1])
    )
    exported = "\n".join(f'    "{alias}",' for alias in sorted(names))
    text = (
        f'"""{title}: {intro}\n\n'
        "Generated by ``tools/gen_namespaces.py`` from the sections of the API reference: do\n"
        'not edit.\n"""\n\n'
        f"from comnum import (\n{imports}\n)\n\n__all__ = [\n{exported}\n]\n"
    )
    return ruff_format(
        sorted_imports(text, name), PACKAGE / f"{name}.py", "tools/gen_namespaces.py"
    )


def outputs() -> dict[str, str]:
    """The text of every namespace, by its module name."""
    by_theme = themes()
    missing = sorted(set(THEMES) - set(by_theme))
    if missing:
        raise SystemExit(f"themes not found in {INDEX.relative_to(ROOT)}: {missing}")
    closed_forms = {
        n.removeprefix(PREFIX): n
        for names in by_theme.values()
        for n in names
        if n.startswith(PREFIX)
    }
    out = {
        THEORY: module(
            THEORY,
            "Closed forms",
            "the error rates, capacities and bounds, ``comnum.theory_<name>`` as\n``comnum.theory.<name>``.",
            closed_forms,
        )
    }
    for theme, name in THEMES.items():
        names = {n: n for n in by_theme[theme] if not n.startswith(PREFIX)}
        out[name] = module(
            name, theme, "the names of this theme of the API reference, as in ``comnum``.", names
        )
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a module is out of date")
    args = ap.parse_args()
    status = 0
    for name, text in outputs().items():
        status |= write_or_check(
            PACKAGE / f"{name}.py", text, args.check, fix="`python tools/gen_namespaces.py`"
        )
    return status


if __name__ == "__main__":
    sys.exit(main())
