"""comnum's Manakov solver against the ``fiber`` of Optilux (GPL-3.0, Octave), recorded.

``tools/record_optilux.py --mode manakov`` runs Optilux (Paolo Serena, University of
Parma, the release of April 2021) under Octave in its unique-field mode with the
Manakov equation (``ismanakov``: the nonlinear phase ``(8/9) γ (|A_x|² + |A_y|²)`` on
both polarisations, no PMD and no birefringence: ``pmdpar = 0`` makes its one waveplate
the identity) on a dual-polarisation WDM field generated by comnum (five 16-QAM channels
at 32 GBd spaced by 50 GHz, root-raised cosine of roll-off 0.1, 16 samples per symbol,
2 dBm per channel split between the polarisations, 2¹¹ symbols, seed 1) over the link of
the benchmark scenario (80 km spans, alpha 0.2 dB/km, D 17 ps/nm/km, no slope, gamma
1.3 /W/km, a fixed symmetric step of 1 km, noiseless amplification of alpha L at the end
of every span), and records in ``tests/oracle/optilux_manakov.npz`` (the provenance in
the ``.json``) the input and the output fields, one row per polarisation, of three
cases: one span without Kerr effect, one span with it, and ten spans.

What the comparison shows, with ``comnum.ManakovSsfm`` at the same step on the same
field:

- the linear span agrees to machine precision (NMSE below 10⁻²⁴) whatever the nonlinear
  step: same dispersion operator, same attenuation, same amplifier, the two
  polarisations propagated alike;
- with ``nonlinear_step="effective_length"``, comnum's step is Optilux's: the Kerr spans
  agree to machine precision too (NMSE 6 · 10⁻²⁷ after one span, 7 · 10⁻²⁵ after ten).
  Optilux's dual-polarisation nonlinear operator with ``ismanakov`` is the rotation of
  both polarisations by the phase of their total power over the effective length of the
  step, exactly comnum's Manakov rotation: no gap is left to the scheme;
- with the midpoint step (the default), the two differ by the weighting of the
  attenuation within the step only: NMSE 6 · 10⁻¹⁰ after one span, 7 · 10⁻⁸ after ten;
  against the step-converged solution (comnum at 0.05 km) both are 3.3 · 10⁻³ away at 1
  km, a step error set by the walk-off of the five channels, not by the attenuation
  (the two schemes within 0.1 % of each other at every step from 0.25 to 4 km);
- OptiCommPy's trapezoidal step smooths the cross-phase modulation of channels that walk
  off within a step: 4.5 · 10⁻³ from Optilux after one span, 0.39 after ten.

Conventions: Optilux writes the Manakov equation with the opposite sign of the imaginary
unit, so the recorder propagated the conjugate of the fields and conjugated the result;
its fields are in sqrt(mW), converted to sqrt(W).
"""

import json

import numpy as np
import pytest

import comnum
from oracle import DIR, missing

if not (DIR / "optilux_manakov.npz").exists():
    missing(
        "tests/oracle/optilux_manakov.npz is missing: run tools/record_optilux.py --mode manakov",
        module=True,
    )
V = dict(np.load(DIR / "optilux_manakov.npz"))
META = json.loads((DIR / "optilux_manakov.json").read_text(encoding="utf-8"))
LINK = META["link"]
REF_STEP_KM = 0.05


def nmse(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.sum(np.abs(a - b) ** 2) / np.sum(np.abs(b) ** 2))


def propagate(
    gamma_w_km: float,
    n_spans: int,
    step_km: float = LINK["step_km"],
    nonlinear_step: str = "midpoint",
) -> np.ndarray:
    fibre = comnum.FiberParams(
        alpha_db_km=LINK["alpha_db_km"],
        d_ps_nm_km=LINK["d_ps_nm_km"],
        gamma_w_km=gamma_w_km,
        span_km=LINK["span_km"],
        n_spans=n_spans,
        fc_hz=LINK["fc_hz"],
    )
    link = comnum.ManakovSsfm(
        fibre, step_km=step_km, nonlinear_step=nonlinear_step, amplification="ideal"
    )
    x, y = link.propagate(V["input"], LINK["fs_hz"])
    return np.stack([x, y])


def test_the_recorded_field_is_a_dual_polarisation_wdm_field_at_1_km_steps():
    """Two polarisations of the same power; 80 steps of 1 km per span with the Kerr
    effect, the whole span in one step without it."""
    assert V["input"].shape[0] == 2
    power_dbm = 10 * np.log10(np.mean(np.abs(V["input"]) ** 2, axis=1) * 1e3)
    assert np.allclose(power_dbm, 2.0 + 10 * np.log10(5 / 2), atol=0.05)
    for case, steps in META["steps_per_span"].items():
        spans = META["cases"][case]["spans"]
        per_span = (
            int(LINK["span_km"] / LINK["step_km"]) if META["cases"][case]["gamma_scale"] else 1
        )
        assert steps == [per_span] * spans, case


@pytest.mark.parametrize("nonlinear_step", ["midpoint", "effective_length"])
def test_the_linear_span_agrees_to_machine_precision(nonlinear_step):
    ours = propagate(0.0, 1, nonlinear_step=nonlinear_step)
    assert nmse(V["linear_1span"], ours) < 1e-24


@pytest.mark.parametrize(
    ("case", "spans", "bound"), [("kerr_1span", 1, 1e-24), ("kerr_10spans", 10, 1e-22)]
)
def test_the_effective_length_step_is_optilux_s_manakov_step(case, spans, bound):
    ours = propagate(LINK["gamma_w_km"], spans, nonlinear_step="effective_length")
    assert nmse(V[case], ours) < bound


@pytest.mark.parametrize(
    ("case", "spans", "bound"), [("kerr_1span", 1, 2e-9), ("kerr_10spans", 10, 2e-7)]
)
def test_the_midpoint_step_differs_by_the_attenuation_within_the_step_only(case, spans, bound):
    ours = propagate(LINK["gamma_w_km"], spans)
    assert nmse(V[case], ours) < bound


def test_both_solvers_are_within_the_step_error_of_the_converged_solution():
    """The step error of the five-channel field at 1 km is set by the walk-off of the
    channels: the two weightings of the attenuation are within 0.1 % of each other."""
    ref = propagate(LINK["gamma_w_km"], 10, REF_STEP_KM)
    optilux = nmse(V["kerr_10spans"], ref)
    ours = nmse(propagate(LINK["gamma_w_km"], 10), ref)
    assert 2e-3 < optilux < 5e-3
    assert abs(ours / optilux - 1.0) < 1e-3
