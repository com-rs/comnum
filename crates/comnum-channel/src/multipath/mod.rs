        let pr = ch.powers()[0];
        assert!((comnum_math::lin2db(ps / pr) - 22.0).abs() < 1e-9);
        assert!(((ch.powers().iter().sum::<f64>() + ps) - 1.0).abs() < 1e-12);
        // E[h(n + m) h*(n)] = p_S e^{j 2π 0.7 f_D m / f_s} + p_R J_0(2π f_D m / f_s)
        let lag = 2500; // 2π f_D m / f_s = π/2
        let mut rng = Rng::new(3);
        let (mut r, mut p) = (C64::new(0.0, 0.0), 0.0);
        let trials = 400;
        for _ in 0..trials {
            let t = ch.draw(lag + 1, &mut rng);
            p += t.coefficient(0, 0, 0, 0).norm_sqr();
            r += t.coefficient(0, lag, 0, 0) * t.coefficient(0, 0, 0, 0).conj();
        }
        let tf = f64::from(trials);
        let want = cis(LOS_DOPPLER_RATIO * PI / 2.0) * ps + C64::from(pr * 0.4720);
        assert!((p / tf - (ps + pr)).abs() < 0.02, "{}", p / tf);
        assert!((r / tf - want).norm() < 0.02, "{} {want}", r / tf);
        // without Doppler the realisation is time invariant and keeps the specular part
        let st = Tdl::new(&Profile::TdlD30.tdl_params(0.0, 30.72e6, 2, 2).unwrap()).unwrap();
        let t = st.draw(16, &mut rng);
