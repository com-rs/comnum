impl Profile {
    /// The specular component `(delay in s, power in dB)` of the Ricean first tap of
    /// TDL-D, TDL-E (TR 38.901 Tables 7.7.2-4 and 7.7.2-5, the "LOS path" rows) and
    /// TDLD30 (TS 38.101-4 Table B.2.1.1-5), in the scale of [`Profile::taps`]; `None` for
    /// the profiles of Rayleigh taps only.
    pub fn specular(&self) -> Option<(f64, f64)> {
        match *self {
            Profile::TdlD { .. } | Profile::TdlD30 => Some((0.0, -0.2)),
            Profile::TdlE { .. } => Some((0.0, -0.03)),
            _ => None,
        }
    }

    /// The same profile with the RMS delay spread `delay_spread_s` (s), for the TR 38.901
    /// profiles TDL-A to TDL-E (§7.7.3); the other profiles are returned unchanged.
    pub fn with_delay_spread(self, delay_spread_s: f64) -> Profile {
        match self {
            Profile::TdlA { .. } => Profile::TdlA { delay_spread_s },
            Profile::TdlB { .. } => Profile::TdlB { delay_spread_s },
            Profile::TdlC { .. } => Profile::TdlC { delay_spread_s },
            Profile::TdlD { .. } => Profile::TdlD { delay_spread_s },
            Profile::TdlE { .. } => Profile::TdlE { delay_spread_s },
            other => other,
        }
    }

    /// The parameters of a [`Tdl`] of this profile: its taps and its specular component.
    ///
    /// # Errors
    /// Those of [`Profile::try_taps`].
    pub fn tdl_params(&self, doppler_hz: f64, sample_rate: f64, n_rx: usize, n_tx: usize) -> Result<TdlParams> {
        Ok(TdlParams { taps: self.try_taps()?, specular: self.specular(), doppler_hz, sample_rate, n_rx, n_tx })
    }
}

/// The nominal RMS delay spread of TR 38.901 Table 7.7.3-1, 100 ns, of the names
/// `tdl-a` to `tdl-e`.
pub const NOMINAL_DELAY_SPREAD_S: f64 = 100e-9;

/// The Rayleigh taps `(delay in s, power in dB)` of the TDL model of TR 38.901 derived
/// from the CDL profile `cdl` (§7.7.4: Tables 7.7.2-1 to 7.7.2-5 repeat the delays and
/// powers of Tables 7.7.1-1 to 7.7.1-5), scaled to `delay_spread_s`. Tap 14 of TDL-E is
/// printed at 20.6519 in Table 7.7.2-5 and 20.6419 in Table 7.7.1-5: the TDL value is kept.
fn tr38901(cdl: CdlProfile, delay_spread_s: f64) -> Result<Vec<(f64, f64)>> {
    ensure(delay_spread_s.is_finite() && delay_spread_s >= 0.0, || {
        format!("the RMS delay spread must be finite and non-negative, got {delay_spread_s}")
    })?;
    Ok(cdl
        .table()
        .iter()
        .enumerate()
        .map(|(n, c)| {
            let delay = if cdl == CdlProfile::E && n == 13 { 20.6519 } else { c.delay };
            (delay * delay_spread_s, c.power_db)
        })
        .collect())
}

/// Return [`Error::Config`] unless a signal of rate `signal` is sampled at the rate
/// `channel` (Hz) at which a channel has put its delays and Doppler shifts on the
/// sampling grid (relative tolerance $10^{-9}$): a channel applied to a signal of another
/// rate would give it delays and Doppler shifts scaled by the ratio of the rates.
pub(crate) fn same_rate(signal: Hertz, channel: f64, what: &str) -> Result<()> {
    let fs = signal.0;
    ensure((fs - channel).abs() <= 1e-9 * channel.abs(), || {
        format!("{what} is sampled at {channel} Hz, the signal at {fs} Hz: build the channel at the rate of the signal")
    })
}

/// The RMS delay spread of a list of taps `(delay, power dB)` (s).
pub fn rms_delay_spread(taps: &[(f64, f64)]) -> f64 {
    let p: Vec<f64> = taps.iter().map(|(_, db)| db2lin(*db)).collect();
    let tot: f64 = p.iter().sum();
    let m1: f64 = taps.iter().zip(&p).map(|((d, _), w)| d * w).sum::<f64>() / tot;
    let m2: f64 = taps.iter().zip(&p).map(|((d, _), w)| d * d * w).sum::<f64>() / tot;
    (m2 - m1 * m1).max(0.0).sqrt()
}

