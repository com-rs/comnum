/// The maximum Doppler shift $f_{D} = v f_{c} / c$ (Hz) of a terminal moving at
/// `speed_mps` (m/s) on the carrier `fc_hz` (Hz), $c$ the speed of light (Clarke 1968).
///
/// The papers give the speed in km/h ($v = $ `kmh / 3.6`) or in mph
/// ($v = 0.447\,04 \times$ `mph`).
///
/// # Examples
/// ```
/// // 60 km/h at 2.5 GHz: about 139 Hz
/// let fd = comnum_channel::multipath::max_doppler_hz(60.0 / 3.6, 2.5e9);
/// assert!((fd - 138.98).abs() < 0.01);
/// ```
pub fn max_doppler_hz(speed_mps: f64, fc_hz: f64) -> f64 {
    speed_mps * fc_hz / SPEED_OF_LIGHT
}

/// The Doppler shift of the specular component of a Ricean tap relative to the maximum
/// Doppler shift, $f_{S} / f_{D} = 0.7$ (TR 38.901 §7.7.2, for TDL-D and TDL-E).
pub const LOS_DOPPLER_RATIO: f64 = 0.7;

/// A power-delay profile.
#[non_exhaustive]
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Profile {
    /// Extended Pedestrian A (TS 36.101), RMS delay spread 43 ns.
    Epa,
    /// Extended Vehicular A (TS 36.101), RMS delay spread 357 ns.
    Eva,
    /// Extended Typical Urban (TS 36.101), RMS delay spread 991 ns.
    Etu,
    /// ITU-R M.1225 (1997), Table 4, outdoor to indoor and pedestrian, channel A (RMS
    /// delay spread 45 ns).
    PedestrianA,
    /// ITU-R M.1225 (1997), Table 4, channel B (750 ns).
    PedestrianB,
    /// ITU-R M.1225 (1997), Table 5, vehicular with high antenna, channel A (370 ns).
    VehicularA,
    /// ITU-R M.1225 (1997), Table 5, channel B (4 000 ns).
    VehicularB,
    /// TR 38.901 Table 7.7.2-1, TDL-A (NLOS, 23 Rayleigh taps), its normalised delays
    /// multiplied by the desired RMS delay spread (§7.7.3, eq. (7.7-1)).
    TdlA {
        /// Desired RMS delay spread (s); Table 7.7.3-1 lists 10, 30, 100, 300 and 1000 ns.
        delay_spread_s: f64,
    },
    /// TR 38.901 Table 7.7.2-2, TDL-B (NLOS, 23 Rayleigh taps).
    TdlB {
        /// Desired RMS delay spread (s).
        delay_spread_s: f64,
    },
    /// TR 38.901 Table 7.7.2-3, TDL-C (NLOS, 24 Rayleigh taps).
    TdlC {
        /// Desired RMS delay spread (s).
        delay_spread_s: f64,
    },
    /// TR 38.901 Table 7.7.2-4, TDL-D (LOS: a Ricean first tap of $K_{1}$ = 13.3 dB, 12
    /// more Rayleigh taps).
    TdlD {
        /// Desired RMS delay spread (s).
        delay_spread_s: f64,
    },
    /// TR 38.901 Table 7.7.2-5, TDL-E (LOS: a Ricean first tap of $K_{1}$ = 22 dB, 13
    /// more Rayleigh taps).
    TdlE {
        /// Desired RMS delay spread (s).
        delay_spread_s: f64,
    },
    /// TS 38.101-4 Table B.2.1.1-2, TDLA30: 12 Rayleigh taps, RMS delay spread 30 ns.
    TdlA30,
    /// TS 38.101-4 Table B.2.1.1-3, TDLB100: 12 Rayleigh taps, 100 ns.
    TdlB100,
    /// TS 38.101-4 Table B.2.1.1-4, TDLC300: 12 Rayleigh taps, 300 ns.
    TdlC300,
    /// TS 38.101-4 Table B.2.1.1-5, TDLD30: a Ricean first tap and 9 Rayleigh taps, 30 ns.
    TdlD30,
    /// An exponential profile of the given RMS delay spread, truncated at five times the
    /// spread, with taps every `resolution_s` seconds (a finite non-negative spread and a
    /// finite positive spacing, which [`Profile::try_taps`] checks).
    Exponential {
        /// RMS delay spread (s).
        rms_delay_s: f64,
        /// Tap spacing (s).
        resolution_s: f64,
    },
}

impl std::str::FromStr for Profile {
    type Err = Error;

    /// The profile of a name: `epa`, `eva`, `etu`, `pedestrian_a` (or `ped_a`),
    /// `pedestrian_b` (`ped_b`), `vehicular_a` (`veh_a`), `vehicular_b` (`veh_b`),
    /// `tdla30`, `tdlb100`, `tdlc300`, `tdld30` (TS 38.101-4), `tdl-a` to `tdl-e` (TR
    /// 38.901, at the nominal delay spread of 100 ns of Table 7.7.3-1; [`Profile::with_delay_spread`]
    /// sets another), case-insensitive.
    ///
    /// # Errors
    /// [`Error::Config`] for another name.
    fn from_str(name: &str) -> Result<Profile> {
        Ok(match name.to_ascii_lowercase().as_str() {
            "epa" => Profile::Epa,
            "eva" => Profile::Eva,
            "etu" => Profile::Etu,
            "pedestrian_a" | "ped_a" => Profile::PedestrianA,
            "pedestrian_b" | "ped_b" => Profile::PedestrianB,
            "vehicular_a" | "veh_a" => Profile::VehicularA,
            "vehicular_b" | "veh_b" => Profile::VehicularB,
            "tdla30" => Profile::TdlA30,
            "tdlb100" => Profile::TdlB100,
            "tdlc300" => Profile::TdlC300,
            "tdld30" => Profile::TdlD30,
            "tdl-a" => Profile::TdlA { delay_spread_s: NOMINAL_DELAY_SPREAD_S },
            "tdl-b" => Profile::TdlB { delay_spread_s: NOMINAL_DELAY_SPREAD_S },
            "tdl-c" => Profile::TdlC { delay_spread_s: NOMINAL_DELAY_SPREAD_S },
            "tdl-d" => Profile::TdlD { delay_spread_s: NOMINAL_DELAY_SPREAD_S },
            "tdl-e" => Profile::TdlE { delay_spread_s: NOMINAL_DELAY_SPREAD_S },
            other => {
                return Err(Error::Config(format!(
                    "unknown profile {other:?}: epa, eva, etu, pedestrian_a, pedestrian_b, vehicular_a, vehicular_b, tdla30, tdlb100, tdlc300, tdld30, tdl-a to tdl-e"
                )));
            }
        })
    }
}

