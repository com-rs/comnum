//! Frequency-selective multipath fading: tapped delay lines with Doppler.
//!
//! A [`Tdl`] channel is a tapped delay line whose taps are independent circular
//! Gaussian processes (Rayleigh fading) of powers $p_{l}$ at delays $\tau_{l}$, every tap
//! varying in time with the Clarke/Jakes Doppler spectrum of the maximum Doppler shift
//! $f_{D}$:
//!
//! $$
//! y\[n\] = \sum_{l} h_{l}\[n\]\, x\[n - d_{l}\], \qquad
//! \mathbb{E}\left\[h_{l}\[n\] h_{l}^{*}\[n + m\]\right\] = p_{l}\, J_{0}(2\pi f_{D} m / f_{s}),
//! $$
//!
//! with the delays rounded to the sampling grid ($d_{l} = \mathrm{round}(\tau_{l} f_{s})$;
//! taps falling on the same sample add their powers) and the powers normalised to a
//! unit total. Each tap is generated by the sum-of-sinusoids model of Zheng & Xiao
//! (2003), with random arrival angles and phases. With MIMO dimensions every tap is an
//! $n_{r} \times n_{t}$ matrix of independent such processes.
//!
//! [`DelayDopplerModel`] draws [`DelayDoppler`] channels: a few discrete paths, each
//! with one delay and one Doppler shift, the model of OTFS.
//!
//! [`Profile`] lists the power-delay profiles of 3GPP TS 36.101 (EPA, EVA, ETU), of
//! ITU-R M.1225 (Pedestrian A and B, Vehicular A and B), of 3GPP TR 38.901 (TDL-A to
//! TDL-E, Tables 7.7.2-1 to 7.7.2-5, their normalised delays scaled to a desired RMS delay
//! spread, §7.7.3) and of 3GPP TS 38.101-4 (TDLA30, TDLB100, TDLC300, TDLD30, Tables
//! B.2.1.1-2 to B.2.1.1-5, the simplified profiles of the conformance tests), and an
//! exponential profile of a given RMS delay spread.
//!
//! The first tap of TDL-D, TDL-E and TDLD30 is Ricean: a specular component
//! ([`Profile::specular`], [`TdlParams::specular`]) of constant amplitude and of Doppler
//! shift $f_{S} = 0.7 f_{D}$ ([`LOS_DOPPLER_RATIO`]; TR 38.901 §7.7.2) at the delay of a
//! Rayleigh tap, $h_{1}\[n\] = \sqrt{p_{S}}\, e^{j(2\pi f_{S} n / f_{s} + \phi)} +
//! h_{1}^{\mathrm{Rayleigh}}\[n\]$, $\phi$ uniform, the K-factor
//! $p_{S}/p_{1}^{\mathrm{Rayleigh}}$ (13.3 dB for TDL-D, 22 dB for TDL-E).
//!
//! # Examples
//! ```
//! use comnum_core::prelude::*;
//! use comnum_channel::fading::Fading;
//! use comnum_channel::multipath::{Profile, Tdl, TdlParams};
//! // static EVA at 15.36 MHz
//! let ch = Tdl::new(&TdlParams { taps: Profile::Eva.taps(), sample_rate: 15.36e6, ..TdlParams::default() })?;
//! let x = Signal::from_stream(vec![C64::new(1.0, 0.0); 64], Hertz(15.36e6))?;
//! let (y, h) = ch.fade(&x, &mut batch_rng(1, 0))?;
//! assert_eq!(y.len(), 64);
//! assert_eq!(h.delays().last(), Some(&39));                     // 2.51 µs at 15.36 MHz
//! # Ok::<(), comnum_core::Error>(())
//! ```
//!
//! # References
//!
//! 1. 3GPP TS 36.101, *E-UTRA; User Equipment (UE) radio transmission and reception*,
//!    Annex B.2 (EPA, EVA, ETU).
//! 2. ITU-R M.1225, *Guidelines for evaluation of radio transmission technologies for
//!    IMT-2000*, 1997 (Pedestrian A and B, Vehicular A and B).
//! 3. 3GPP TR 38.901 V19.5.0, *Study on channel model for frequencies from 0.5 to 100
//!    GHz*, §7.7.2 (Tables 7.7.2-1 to 7.7.2-5) and §7.7.3 (scaling of delays).
//! 4. 3GPP TS 38.101-4 V19.4.0, *NR; UE radio transmission and reception; Part 4:
//!    Performance requirements*, Annex B.2.1 (Tables B.2.1.1-1 to B.2.1.1-5).
//! 5. R. H. Clarke, "A statistical theory of mobile-radio reception," *Bell Syst. Tech.
//!    J.*, 47(6), 957–1000, 1968; W. C. Jakes, *Microwave Mobile Communications*, Wiley,
//!    1974.
//! 6. Y. R. Zheng and C. Xiao, "Simulation models with correct statistical properties for
//!    Rayleigh fading channels," *IEEE Trans. Commun.*, 51(6), 920–928, 2003.
//! 7. P. Raviteja, Y. Hong, E. Viterbo and E. Biglieri, "Practical pulse-shaping
//!    waveforms for reduced-cyclic-prefix OTFS," *IEEE Trans. Veh. Technol.*, 68(1),
//!    957–961, 2019.

